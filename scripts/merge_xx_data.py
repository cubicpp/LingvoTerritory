def parse_pitch(raw: str) -> list:
    digits = [int(c) for c in raw if c.isdigit() and 1 <= int(c) <= 5]
    if len(digits) == 0: return []
    if len(digits) == 1: return [digits[0], digits[0], digits[0]]
    if len(digits) == 2: return [digits[0], round((digits[0]+digits[1])/2), digits[1]]
    return digits[:3]

# Map tone category names to numeric indices
