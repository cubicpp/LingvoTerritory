def find_coords(name: str) -> tuple | None:
    """Try to find lat/lng for a point name."""
    # Exact match
    if name in CITY_COORDS:
        return CITY_COORDS[name]
    # Try without parenthetical notes
    base = name.split("(")[0].strip()
    if base in CITY_COORDS:
        return CITY_COORDS[base]
    # Try matching the first 2 characters (usually the city name)
    if len(base) >= 2:
        for city, coords in CITY_COORDS.items():
            if base.startswith(city) or city.startswith(base[:2]):
                return coords
    # Fallback: use coordinates of an existing nearby point
    for pid, p in point_by_id.items():
        if p.get("lat") and p.get("lng"):
            if base in pid or pid in base or base in p.get("name", ""):
                return (p["lat"], p["lng"])
    return None

